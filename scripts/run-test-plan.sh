#!/usr/bin/env bash
# run-test-plan.sh — the test-plan §5 "Full plan run" sweep entry point
# (test-plan.md §5: "Phase 2 adds it").
#
# Usage: scripts/run-test-plan.sh [phase]        # phase defaults to 2
#
# What it does, in order:
#   1. runs the phase's multi-process catalogue (`go test ./internal/mptest/...
#      -count=1 -v`) and keeps the transcript;
#   2. runs the REST of the suite (`go test` over every other package,
#      -count=1) and keeps its transcript;
#   3. GENERATES docs/test-results/phase-<P>/index.md and summary.md from the
#      transcripts — a row's outcome is never typed by hand (design review
#      fix 4);
#   4. promotes the run's evidence deliberately: the rows write their
#      artifacts into the scratch root (/tmp/ledgerboard-scratch/evidence,
#      review addendum §8), and this script — the author's explicit act —
#      copies the per-row directories and the two transcripts into
#      docs/test-results/phase-<P>/. A plain `go test` run therefore never
#      dirties the tree; QA can re-run and get a clean tree.
#
# Exit status: non-zero if the MP catalogue or the rest-of-suite failed.
set -uo pipefail
cd "$(dirname "$0")/.."

PHASE="${1:-2}"
SCRATCH_EV="/tmp/ledgerboard-scratch/evidence/phase-$PHASE"
DOCS_EV="docs/test-results/phase-$PHASE"
MP_TXT="$DOCS_EV/multiprocess.txt"
REG_TXT="$DOCS_EV/regression.txt"

mkdir -p "$SCRATCH_EV" "$DOCS_EV"

echo "== run-test-plan.sh: phase $PHASE — multi-process catalogue"
go test ./internal/mptest/... -count=1 -v 2>&1 | tee "$SCRATCH_EV-transcript.txt"
MP=$?

echo "== run-test-plan.sh: the rest of the suite"
go test $(go list ./... | grep -v '/internal/mptest') -count=1 2>&1 | tee "$SCRATCH_EV-regression.txt"
REST=$?

# index.md — generated from the transcript, never hand-typed.
{
  echo "# Phase $PHASE — run index (generated by scripts/run-test-plan.sh)"
  echo
  echo "One line per row, exactly as \`go test -v\` reported it. Transcript: \`multiprocess.txt\`."
  echo
  echo "| Row | Result | Duration |"
  echo "|---|---|---|"
  grep -E '^--- (PASS|FAIL|SKIP): ' "$SCRATCH_EV-transcript.txt" \
    | sed -E 's/^--- (PASS|FAIL|SKIP): ([^ ]+) \(([^)]*)\).*/| \2 | \1 | \3 |/'
  echo
  echo "Totals: $(grep -c '^--- PASS' "$SCRATCH_EV-transcript.txt") PASS · $(grep -c '^--- FAIL' "$SCRATCH_EV-transcript.txt") FAIL · $(grep -c '^--- SKIP' "$SCRATCH_EV-transcript.txt") SKIP"
} > "$DOCS_EV/index.md"

# summary.md — the run's verdict header and the tail of both transcripts.
{
  echo "# Phase $PHASE — run summary (generated by scripts/run-test-plan.sh)"
  echo
  echo "- MP catalogue (\`go test ./internal/mptest -count=1 -v\`): exit $MP"
  echo "- Rest of suite (\`go test\` over every other package, -count=1): exit $REST"
  echo
  echo "Full transcripts: \`multiprocess.txt\` (MP rows), \`regression.txt\` (everything)."
} > "$DOCS_EV/summary.md"

# Deliberate promotion: scratch evidence -> docs (the author's act; re-running
# the suite alone leaves the tree clean — review addendum §8).
#
# finding-*.md files are hand-authored documents (A12, A14, …) that live inside
# row directories. They are NOT run artifacts: the run-5 promotion deleted the
# committed finding-A12.md with the row dirs (47fb64a) — back them up before
# the sweep and restore them after, so a promotion can never eat a finding.
FIND_BAK="$(mktemp -d)"
(cd "$DOCS_EV" && find . -path './T-*/finding-*.md' -type f -print0) \
  | while IFS= read -r -d '' f; do
      mkdir -p "$FIND_BAK/$(dirname "$f")"
      cp -a "$DOCS_EV/$f" "$FIND_BAK/$f"
    done
cp "$SCRATCH_EV-transcript.txt" "$MP_TXT"
cp "$SCRATCH_EV-regression.txt" "$REG_TXT"
rm -rf "$DOCS_EV"/T-*/
find "$SCRATCH_EV" -maxdepth 1 -type d -name 'T-*' -exec cp -a {} "$DOCS_EV"/ \;
(cd "$FIND_BAK" && find . -type f -print0) \
  | while IFS= read -r -d '' f; do
      mkdir -p "$DOCS_EV/$(dirname "$f")"
      cp -a "$FIND_BAK/$f" "$DOCS_EV/$f"
    done
rm -rf "$FIND_BAK"

echo "== run-test-plan.sh: MP=$MP rest=$REST — index.md/summary.md/evidence promoted to $DOCS_EV"
[ "$MP" -eq 0 ] && [ "$REST" -eq 0 ]
